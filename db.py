PG_VIEW = SCHEMA_VIEW.replace("date('now','localtime')", "to_char(now() AT TIME ZONE 'Asia/Dhaka', 'YYYY-MM-DD')")

ID_TABLES = ("jamaats", "users", "subscribers", "payments")


class _Row(dict):
    """A result row that works like sqlite3.Row: row["name"], row[0], row.name (in templates)."""
    def __getitem__(self, k):
        if isinstance(k, int):
            return list(self.values())[k]
        return dict.__getitem__(self, k)


def _row_factory(cursor):
    names = [c.name for c in cursor.description] if cursor.description else []
    return lambda values: _Row(zip(names, values))


def _translate(sql):
    """SQLite-style SQL (as written in app.py) -> PostgreSQL."""
    sql = sql.replace("?", "%s")
    sql = sql.replace("IS NOT %s", "IS DISTINCT FROM %s")
    sql = re.sub(r"\bLIKE\b", "ILIKE", sql)
    sql = sql.replace("CAST(local_id AS INTEGER)", "(CASE WHEN local_id ~ '^[0-9]+$' THEN local_id::bigint END)")
    return sql


class _Cursor:
    def __init__(self, cur, lastrowid=None):
        self._cur, self.lastrowid = cur, lastrowid

    def fetchone(self):
        return self._cur.fetchone()

    def fetchall(self):
        return self._cur.fetchall()

    def __iter__(self):
        return iter(self._cur)

    def __getattr__(self, name):
        return getattr(self._cur, name)


class PgConnection:
    """Gives a psycopg connection the small sqlite3-style API the application uses."""
    def __init__(self, raw):
        self.raw = raw

    def execute(self, sql, params=()):
        named = isinstance(params, dict)
        if named:                                   # :name style parameters -> %(name)s
            sql = re.sub(r"(?<![:\w]):(\w+)", r"%(\1)s", sql)
        sql = _translate(sql)
        m = re.match(r"\s*INSERT\s+INTO\s+(\w+)", sql, re.I)
        want_id = bool(m and m.group(1).lower() in ID_TABLES and "RETURNING" not in sql.upper()
                       and "ON CONFLICT" not in sql.upper())
        if want_id:
            sql += " RETURNING id"
        cur = self.raw.execute(sql, params if named else (tuple(params) if params else None))
        if want_id:
            row = cur.fetchone()
            return _Cursor(cur, row["id"] if row else None)
        return _Cursor(cur)

    def executescript(self, sql):
        self.raw.execute(sql)

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        self.raw.close()


def connect(path=None):
    if IS_PG and path is None:
        import psycopg
        return PgConnection(psycopg.connect(DATABASE_URL, row_factory=_row_factory, connect_timeout=15))
    con = sqlite3.connect(path or DB_PATH)
    con.row_factory = sqlite3.Row
    con.execute("PRAGMA foreign_keys = ON")
    return con


def sync_sequences(con):
    """PostgreSQL only: after rows were inserted with explicit IDs, move the counters past the biggest ID."""
    if not IS_PG:
        return
    for t in ID_TABLES:
        con.execute(f"SELECT setval(pg_get_serial_sequence('{t}','id'), "
                    f"COALESCE((SELECT MAX(id) FROM {t}), 0) + 1, false)")


def get_db():
    if "db" not in g:
        g.db = connect()
    return g.db


def close_db(_exc=None):
    con = g.pop("db", None)
    if con is not None:
        con.close()


def _cols(con, table):
    return {r["name"] for r in con.execute(f"PRAGMA table_info({table})")}


def _migrate(con):
    """Upgrade an older database in place - existing data is kept."""
    uc = _cols(con, "users")
    if "role" not in uc:
        con.execute("ALTER TABLE users ADD COLUMN role TEXT NOT NULL DEFAULT 'admin'")
    if "jamaat_id" not in uc:
        con.execute("ALTER TABLE users ADD COLUMN jamaat_id INTEGER REFERENCES jamaats(id)")
    if "local_id" not in _cols(con, "subscribers"):
        con.execute("ALTER TABLE subscribers ADD COLUMN local_id TEXT")
    con.execute("CREATE INDEX IF NOT EXISTS ix_sub_local ON subscribers(jamaat_id, local_id)")


def init_db(path=None):
    con = connect(path)
    if IS_PG and path is None:
        con.executescript(PG_TABLES)
        con.executescript(PG_VIEW)
    else:
        con.executescript(SCHEMA_TABLES)
        _migrate(con)
        con.executescript(SCHEMA_VIEW)
    con.commit()
    con.close()
